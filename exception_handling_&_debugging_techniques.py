print("""
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
TYPE 1: SYNTAX ERROR
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
A syntax error occurs when Python cannot understand the
code because of wrong grammar or spelling mistakes.
These are caught BEFORE the program runs.

Example 1 - Missing colon:
  if x > 5       ← should be: if x > 5:
      print("hi")

Example 2 - Missing closing bracket:
  print("Hello"  ← should be: print("Hello")

Example 3 - Wrong indentation:
  def greet():
  print("Hi")    ← should be indented inside function

Example 4 - Misspelled keyword:
  whille True:   ← should be: while True:

Example 5 - Missing quotes:
  name = John    ← should be: name = "John"

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
TYPE 2: RUNTIME ERROR
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
A runtime error occurs WHILE the program is running.
The code looks correct but fails during execution.

Example 1 - ZeroDivisionError:
  x = 10 / 0    ← cannot divide by zero

Example 2 - FileNotFoundError:
  open("ghost.txt", "r")  ← file does not exist

Example 3 - ValueError:
  int("hello")  ← cannot convert text to integer

Example 4 - IndexError:
  my_list = [1, 2, 3]
  print(my_list[10])  ← index 10 does not exist

Example 5 - NameError:
  print(age)    ← variable 'age' was never defined

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
TYPE 3: LOGICAL ERROR
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
A logical error means the program runs without crashing
but gives WRONG results. No error message is shown.
These are the hardest to find!

Example 1 - Wrong operator:
  area = length + width   ← should be: length * width

Example 2 - Wrong condition:
  if age > 18:            ← should be: if age >= 18:
      print("Adult")      ← misses people exactly 18

Example 3 - Off by one error:
  for i in range(1, 10):  ← misses 10, should be range(1, 11)

Example 4 - Wrong average formula:
  avg = a + b / 2         ← should be: avg = (a + b) / 2

Example 5 - Subtraction instead of addition:
  total = price - tax     ← should be: total = price + tax
""")

